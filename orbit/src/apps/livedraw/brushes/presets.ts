type Over = Omit<Partial<Brush>, 'dynamics' | 'jitter' | 'dual' | 'taper'> & { dynamics?: Partial<Brush['dynamics']>; jitter?: Partial<Brush['jitter']>; dual?: Partial<Brush['dual']>; taper?: Partial<Brush['taper']> };
const make = (o: Over & { id: string; name: string; group: string }): Brush => ({
  ...BASE,
  ...o,
  dual: { ...BASE.dual, ...o.dual },
  jitter: { ...BASE.jitter, ...o.jitter },
  taper: { ...BASE.taper, ...o.taper },
  dynamics: { ...BASE.dynamics, ...o.dynamics },
  builtin: true,
});

